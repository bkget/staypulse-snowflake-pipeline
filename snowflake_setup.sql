-- snowflake_setup.sql  |  Run All in one Snowsight worksheet, top to bottom.
-- Before running: replace <YOUR_SNOWFLAKE_USERNAME> (2 places, step 6) and <PUBLIC_KEY_BODY> (step 8).
-- Verified against a Snowflake trial account. snowflake_smoke_test.sql checks the result.

-- 0) Account guardrails (ACCOUNTADMIN) ---------------------------------------------
USE ROLE ACCOUNTADMIN;
SELECT CURRENT_REGION();                                   -- note it: Cortex availability depends on it
ALTER ACCOUNT SET STATEMENT_TIMEOUT_IN_SECONDS = 3600;     -- default is 2 days
CREATE OR REPLACE RESOURCE MONITOR RM_STAYPULSE            -- warehouses only, not AI or serverless spend
  WITH CREDIT_QUOTA = 30 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 50 PERCENT DO NOTIFY
           ON 80 PERCENT DO NOTIFY
           ON 95 PERCENT DO SUSPEND
           ON 100 PERCENT DO SUSPEND_IMMEDIATE;
REVOKE DATABASE ROLE SNOWFLAKE.CORTEX_USER FROM ROLE PUBLIC;   -- Cortex is open to everyone by default

-- 1) Roles --------------------------------------------------------------------------
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS SP_LOADER      COMMENT = 'Writes RAW only';
CREATE ROLE IF NOT EXISTS SP_TRANSFORMER COMMENT = 'Reads RAW, writes STAGING to MARTS, calls Cortex';
CREATE ROLE IF NOT EXISTS SP_ENGINEER    COMMENT = 'You: inherits both, so you never need ACCOUNTADMIN';
GRANT ROLE SP_LOADER      TO ROLE SP_ENGINEER;
GRANT ROLE SP_TRANSFORMER TO ROLE SP_ENGINEER;
GRANT ROLE SP_ENGINEER    TO ROLE SYSADMIN;

-- 2) Warehouses (two, X-Small, auto-suspend 60 s) -------------------------------------
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS LOAD_WH WITH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE STATEMENT_TIMEOUT_IN_SECONDS = 1800
  COMMENT = 'PUT and COPY INTO';
CREATE WAREHOUSE IF NOT EXISTS TRANSFORM_WH WITH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE STATEMENT_TIMEOUT_IN_SECONDS = 3600
  COMMENT = 'dbt, Snowpark, Cortex and FORECAST';
USE ROLE ACCOUNTADMIN;                                     -- only ACCOUNTADMIN can attach a monitor
ALTER WAREHOUSE LOAD_WH      SET RESOURCE_MONITOR = RM_STAYPULSE;
ALTER WAREHOUSE TRANSFORM_WH SET RESOURCE_MONITOR = RM_STAYPULSE;

-- 3) Database and schemas (managed access: pipelines cannot grant themselves more) ----
USE ROLE SYSADMIN;
CREATE DATABASE IF NOT EXISTS STAYPULSE DATA_RETENTION_TIME_IN_DAYS = 7;   -- Enterprise edition allows up to 90
CREATE SCHEMA IF NOT EXISTS STAYPULSE.RAW          WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS STAYPULSE.STAGING      WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS STAYPULSE.INTERMEDIATE WITH MANAGED ACCESS;   -- stores the paid-for Cortex output
CREATE SCHEMA IF NOT EXISTS STAYPULSE.SNAPSHOTS    WITH MANAGED ACCESS;   -- SCD2 history
CREATE SCHEMA IF NOT EXISTS STAYPULSE.MARTS        WITH MANAGED ACCESS;

-- 4) Grants -------------------------------------------------------------------------
USE ROLE SECURITYADMIN;
GRANT USAGE ON WAREHOUSE LOAD_WH      TO ROLE SP_LOADER;
GRANT USAGE ON WAREHOUSE TRANSFORM_WH TO ROLE SP_TRANSFORMER;
GRANT OPERATE ON WAREHOUSE LOAD_WH      TO ROLE SP_ENGINEER;           -- manual suspend and resume
GRANT OPERATE ON WAREHOUSE TRANSFORM_WH TO ROLE SP_ENGINEER;
GRANT USAGE ON DATABASE STAYPULSE TO ROLE SP_LOADER;
GRANT USAGE ON DATABASE STAYPULSE TO ROLE SP_TRANSFORMER;

-- Loader writes RAW; future grants also cover the stage and tables created later
GRANT USAGE, CREATE TABLE ON SCHEMA STAYPULSE.RAW TO ROLE SP_LOADER;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA STAYPULSE.RAW TO ROLE SP_LOADER;
GRANT READ, WRITE ON FUTURE STAGES IN SCHEMA STAYPULSE.RAW TO ROLE SP_LOADER;
GRANT USAGE ON FUTURE FILE FORMATS IN SCHEMA STAYPULSE.RAW TO ROLE SP_LOADER;

-- Transformer reads RAW and owns everything downstream
GRANT USAGE ON SCHEMA STAYPULSE.RAW TO ROLE SP_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA STAYPULSE.RAW TO ROLE SP_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE FUNCTION, CREATE STAGE ON SCHEMA STAYPULSE.STAGING      TO ROLE SP_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE FUNCTION, CREATE STAGE ON SCHEMA STAYPULSE.INTERMEDIATE TO ROLE SP_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE FUNCTION, CREATE STAGE ON SCHEMA STAYPULSE.SNAPSHOTS    TO ROLE SP_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE FUNCTION, CREATE STAGE ON SCHEMA STAYPULSE.MARTS        TO ROLE SP_TRANSFORMER;
GRANT CREATE SNOWFLAKE.ML.FORECAST ON SCHEMA STAYPULSE.MARTS TO ROLE SP_TRANSFORMER;   -- model object lives in MARTS

-- 5) Database roles of the SNOWFLAKE database need ACCOUNTADMIN ----------------------
USE ROLE ACCOUNTADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER  TO ROLE SP_TRANSFORMER;
GRANT DATABASE ROLE SNOWFLAKE.USAGE_VIEWER TO ROLE SP_ENGINEER;     -- credit and Cortex usage views

-- 6) Users --------------------------------------------------------------------------
USE ROLE SECURITYADMIN;
CREATE USER IF NOT EXISTS SVC_PIPELINE TYPE = SERVICE DEFAULT_ROLE = SP_TRANSFORMER
  DEFAULT_WAREHOUSE = TRANSFORM_WH COMMENT = 'Airflow and Snowpark, key-pair only';
GRANT ROLE SP_LOADER      TO USER SVC_PIPELINE;     -- each task picks its role explicitly
GRANT ROLE SP_TRANSFORMER TO USER SVC_PIPELINE;
GRANT ROLE SP_ENGINEER TO USER <YOUR_SNOWFLAKE_USERNAME>;
ALTER USER <YOUR_SNOWFLAKE_USERNAME> SET DEFAULT_ROLE = SP_ENGINEER DEFAULT_WAREHOUSE = TRANSFORM_WH;

-- 7) File formats and one internal stage (SYSADMIN owns them; future grants above apply) --
USE ROLE SYSADMIN;
USE SCHEMA STAYPULSE.RAW;
CREATE FILE FORMAT IF NOT EXISTS FF_CSV_GZ TYPE = CSV PARSE_HEADER = TRUE
  FIELD_OPTIONALLY_ENCLOSED_BY = '"' EMPTY_FIELD_AS_NULL = TRUE NULL_IF = ('', 'N/A', 'NULL')
  ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE ENCODING = 'UTF8' COMPRESSION = AUTO;
CREATE FILE FORMAT IF NOT EXISTS FF_JSON TYPE = JSON COMPRESSION = AUTO;
CREATE STAGE IF NOT EXISTS STG_LANDING ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE') DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'airbnb/, weather/, bookings/ subfolders';

-- 8) Attach the service user's public key (paste the output of the grep command) ------
USE ROLE SECURITYADMIN;
ALTER USER SVC_PIPELINE SET RSA_PUBLIC_KEY = '<PUBLIC_KEY_BODY>';
